// Writes src/shared/spanish-plurals.ts, the Spanish `-es` plurals the normalizer looks up (spec
// 4.15), from the Spanish seed. Run it after changing src/shared/seed/ingredients-es.ts:
//
//   yarn seed:es-plurals
//
// The seed test fails while the file is stale, or when a plural collides with an English name.
import { buildSpanishEsPlurals } from '../src/shared/seed/es-plurals.ts';
import { seedEsEntries } from '../src/shared/seed/ingredients-es.ts';

const plurals = buildSpanishEsPlurals(seedEsEntries().map((e) => e.name));
const lines = Object.entries(plurals).map(([plural, singular]) => `  ${plural}: '${singular}',`);

const out = `// Generated by scripts/gen-es-plurals.ts from src/shared/seed/ingredients-es.ts (spec 4.15). Do
// not edit by hand: change the Spanish seed and run \`yarn seed:es-plurals\`.
//
// Spanish plurals the English suffix rules get wrong, by plural, each with its singular.

export const SPANISH_ES_PLURALS: Readonly<Record<string, string>> = {
${lines.join('\n')}
};
`;

const path = new URL('../src/shared/spanish-plurals.ts', import.meta.url);
await Deno.writeTextFile(path, out);
console.log(`Wrote ${path.pathname} (${lines.length} plurals)`);
