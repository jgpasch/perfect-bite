// Writes a migration that upserts the system categories and seed ingredients from src/shared/seed/
// (spec 6.2), so the SQL copy of the seed is generated, never hand-edited. Run it after changing
// the seed:
//
//   yarn db:seed-sql
//
// Seed rows overwrite only rows the seed owns (`categorized_by = 'seed'`) or that aren't
// categorized yet, so a model or admin answer is never replaced. Every seed name gets its language
// (`lang`: 'en' for ingredients.ts, 'es' for ingredients-es.ts) where it has none, and the Spanish
// seed's links (spec 4.15) win over a model's on the same name; an admin's link is kept. A link the
// seed made and no longer lists is cleared.
import { normalizeIngredientName, seedEntries, seedEsEntries, SYSTEM_CATEGORIES } from '../src/shared/index.ts';

const sql = (text: string) => `'${text.replaceAll("'", "''")}'`;
const key = (name: string) => sql(normalizeIngredientName(name));

function timestamp(now: Date): string {
  return now.toISOString().replace(/\D/g, '').slice(0, 14);
}

/** The new migration's timestamp: now, or a second after the newest migration if that's later, so it always runs last. */
async function nextTimestamp(dir: URL): Promise<string> {
  let latest = '';
  for await (const f of Deno.readDir(dir)) {
    const stamp = /^(\d{14})_/.exec(f.name)?.[1];
    if (stamp && stamp > latest) latest = stamp;
  }
  const stamp = timestamp(new Date());
  if (stamp > latest) return stamp;
  const [, y, mo, d, h, mi, s] = /^(\d{4})(\d{2})(\d{2})(\d{2})(\d{2})(\d{2})$/.exec(latest)!.map(Number);
  return timestamp(new Date(Date.UTC(y, mo - 1, d, h, mi, s + 1)));
}

const entries = seedEntries();
const esEntries = seedEsEntries();
const links = esEntries.filter((e) => e.sameAs !== null);
const categoryRows = SYSTEM_CATEGORIES.map((c, rank) => `  (${sql(c.id)}, ${sql(c.slug)}, ${sql(c.name)}, ${rank})`);
const rows = (list: readonly { name: string; category: string; unit: string }[]) =>
  list.map((e) => `  (${key(e.name)}, ${sql(e.name)}, ${sql(e.category)}, ${sql(e.unit)})`).join(',\n');

/** Upserts one seed's rows with their language. Targets (English) go in before the names that link to them. */
const upsert = (lang: 'en' | 'es', list: readonly { name: string; category: string; unit: string }[]) => `
insert into public.ingredients
  (normalized_name, display_name, default_category_id, status, is_grocery_item, categorized_by, household_count, default_unit, lang)
select s.normalized_name, s.display_name, c.id, 'categorized', true, 'seed', 1000, s.default_unit, ${sql(lang)}
from (values
${rows(list)}
) as s (normalized_name, display_name, slug, default_unit)
join public.categories c on c.slug = s.slug
on conflict (normalized_name) do update set
  display_name = excluded.display_name,
  default_category_id = excluded.default_category_id,
  status = 'categorized',
  is_grocery_item = true,
  categorized_by = 'seed',
  household_count = greatest(public.ingredients.household_count, excluded.household_count),
  default_unit = excluded.default_unit,
  lang = excluded.lang
where public.ingredients.categorized_by = 'seed' or public.ingredients.status <> 'categorized';

-- Rows the seed doesn't own still learn their language.
update public.ingredients i set lang = ${sql(lang)}
from (values
${list.map((e) => `  (${key(e.name)})`).join(',\n')}
) as s (normalized_name)
where i.normalized_name = s.normalized_name and i.lang is null;
`;

const out = `-- Generated by scripts/gen-seed-sql.ts from src/shared/seed/ (spec 6.2, 4.15). Do not edit by
-- hand: change the seed and run \`yarn db:seed-sql\`, which writes a new migration.
-- ${SYSTEM_CATEGORIES.length} categories, ${entries.length} English and ${esEntries.length} Spanish ingredients, ${links.length} links.
-- household_count is high so seeds pass the autocomplete filter (6.5).

insert into public.categories (id, slug, name, default_rank) values
${categoryRows.join(',\n')}
on conflict (id) do update set slug = excluded.slug, name = excluded.name, default_rank = excluded.default_rank;
${upsert('en', entries)}${upsert('es', esEntries)}
-- The Spanish seed's links (linked_by 'seed'). They replace a model's link on the same name; an
-- admin's stays. A seed link the seed no longer lists is cleared first.
update public.ingredients set same_as = null, linked_by = null
where linked_by = 'seed' and normalized_name not in (
${links.map((e) => `  ${key(e.name)}`).join(',\n')}
);

update public.ingredients i set same_as = l.same_as, linked_by = 'seed'
from (values
${links.map((e) => `  (${key(e.name)}, ${key(e.sameAs!)})`).join(',\n')}
) as l (normalized_name, same_as)
where i.normalized_name = l.normalized_name
  and i.linked_by is distinct from 'admin'
  and (i.same_as is distinct from l.same_as or i.linked_by is distinct from 'seed');
`;

const dir = new URL('../supabase/migrations/', import.meta.url);
const path = new URL(`${await nextTimestamp(dir)}_seed_catalog.sql`, dir);
await Deno.writeTextFile(path, out);
console.log(`Wrote ${path.pathname} (${entries.length} + ${esEntries.length} ingredients, ${links.length} links)`);
