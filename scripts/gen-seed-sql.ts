// Writes a migration that upserts the system categories and seed ingredients from src/shared/seed/
// (spec 6.2), so the SQL copy of the seed is generated, never hand-edited. Run it after changing
// the seed:
//
//   yarn db:seed-sql
//
// Seed rows overwrite only rows the seed owns (`categorized_by = 'seed'`) or that aren't
// categorized yet, so a model or admin answer is never replaced.
import { normalizeIngredientName, seedEntries, SYSTEM_CATEGORIES } from '../src/shared/index.ts';

const sql = (text: string) => `'${text.replaceAll("'", "''")}'`;

function timestamp(now: Date): string {
  return now.toISOString().replace(/\D/g, '').slice(0, 14);
}

const entries = seedEntries();
const categoryRows = SYSTEM_CATEGORIES.map((c, rank) => `  (${sql(c.id)}, ${sql(c.slug)}, ${sql(c.name)}, ${rank})`);
const ingredientRows = entries.map(
  (e) => `  (${sql(normalizeIngredientName(e.name))}, ${sql(e.name)}, ${sql(e.category)}, ${sql(e.unit)})`,
);

const out = `-- Generated by scripts/gen-seed-sql.ts from src/shared/seed/ (spec 6.2). Do not edit by hand:
-- change the seed and run \`yarn db:seed-sql\`, which writes a new migration.
-- ${SYSTEM_CATEGORIES.length} categories, ${entries.length} ingredients. household_count is high so seeds pass
-- the autocomplete filter (6.5).

insert into public.categories (id, slug, name, default_rank) values
${categoryRows.join(',\n')}
on conflict (id) do update set slug = excluded.slug, name = excluded.name, default_rank = excluded.default_rank;

insert into public.ingredients
  (normalized_name, display_name, default_category_id, status, is_grocery_item, categorized_by, household_count, default_unit)
select s.normalized_name, s.display_name, c.id, 'categorized', true, 'seed', 1000, s.default_unit
from (values
${ingredientRows.join(',\n')}
) as s (normalized_name, display_name, slug, default_unit)
join public.categories c on c.slug = s.slug
on conflict (normalized_name) do update set
  display_name = excluded.display_name,
  default_category_id = excluded.default_category_id,
  status = 'categorized',
  is_grocery_item = true,
  categorized_by = 'seed',
  household_count = greatest(public.ingredients.household_count, excluded.household_count),
  default_unit = excluded.default_unit
where public.ingredients.categorized_by = 'seed' or public.ingredients.status <> 'categorized';
`;

const path = new URL(`../supabase/migrations/${timestamp(new Date())}_seed_catalog.sql`, import.meta.url);
await Deno.writeTextFile(path, out);
console.log(`Wrote ${path.pathname} (${entries.length} ingredients)`);
