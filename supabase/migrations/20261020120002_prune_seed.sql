select i.normalized_name
from public.ingredients i
join pruned_seed p on p.normalized_name = i.normalized_name
where i.categorized_by = 'seed'
  and not exists (select 1 from public.ingredient_households u where u.ingredient_name = i.normalized_name)
  and not exists (select 1 from public.list_items u where u.ingredient_name = i.normalized_name)
  and not exists (select 1 from public.recipe_ingredients u where u.ingredient_name = i.normalized_name)
  and not exists (select 1 from public.ingredient_usage u where u.ingredient_name = i.normalized_name)
  and not exists (select 1 from public.ingredient_unit_usage u where u.ingredient_name = i.normalized_name)
  and not exists (select 1 from public.household_staples u where u.ingredient_name = i.normalized_name)
  and not exists (select 1 from public.household_category_overrides u where u.ingredient_name = i.normalized_name);

-- A row something outside the set links to stays, so the delete never breaks a same_as.
delete from doomed d
where exists (
  select 1 from public.ingredients t
  where t.same_as = d.normalized_name
    and not exists (select 1 from doomed o where o.normalized_name = t.normalized_name)
);

delete from public.ingredients i
using doomed d
where i.normalized_name = d.normalized_name;

drop table pruned_seed, doomed;
