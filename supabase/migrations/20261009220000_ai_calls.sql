-- AI call log, copied from stash: one row per model attempt made by `runAiTask`, successful or
-- not, with the exact instructions and prompt sent, the output, tokens and timing. Used to
-- debug prompts and watch cost from an admin view; never read by the app.
--
-- Privacy (spec 6.5): no user id and nothing else that links a call to who made it. The
-- prompts hold ingredient names typed by users, so: service role only (no client grants, RLS
-- on with no policies), and rows expire after 30 days.

create table public.ai_calls (
  id uuid primary key,                       -- generated by runAiTask
  created_at timestamptz not null default now(),
  task text not null,                        -- AiTaskName, e.g. 'categorize'
  model text not null,                       -- 'provider:model'
  prompt_version text not null,
  status text not null check (status in ('ok', 'api_error', 'invalid_output', 'timeout', 'error')),
  instructions text not null,
  prompt text not null,
  output jsonb,                              -- schema-validated output; null on failure
  response_text text,                        -- raw model text, kept for invalid output too
  finish_reason text,
  input_tokens integer,
  output_tokens integer,
  cached_input_tokens integer,
  reasoning_tokens integer,
  duration_ms integer not null,
  error text,
  fallback_of uuid references public.ai_calls on delete set null  -- the failed primary attempt
);
create index ai_calls_created_at_idx on public.ai_calls (created_at desc);

revoke all on table public.ai_calls from anon, authenticated;
alter table public.ai_calls enable row level security;

-- Retention: drop rows older than 30 days, daily at 03:17 UTC.
create extension if not exists pg_cron;
select cron.schedule(
  'ai-calls-retention',
  '17 3 * * *',
  $$delete from public.ai_calls where created_at < now() - interval '30 days'$$
);
