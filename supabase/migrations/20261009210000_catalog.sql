-- Catalog and per-user preferences (spec 5, 6.2). Mirrors the app's SQLite tables so the
-- device's data can be pushed up (dev push now, M5 sync later).

-- ---------------------------------------------------------------------------
-- Categories: system ones (owner_user_id null, fixed ids shared with the app bundle) and
-- each user's custom ones.
-- ---------------------------------------------------------------------------

create table public.categories (
  id            uuid primary key,
  slug          text unique,                                    -- e.g. 'produce'; null for custom
  name          text not null,
  owner_user_id uuid references auth.users on delete cascade,  -- null = system category
  default_rank  int,                                            -- default store-walk order (system)
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index categories_owner_user_id_idx on public.categories (owner_user_id);

create trigger categories_set_updated_at
  before insert or update on public.categories
  for each row execute function private.set_updated_at();

alter table public.categories enable row level security;

revoke all on table public.categories from anon, authenticated;
grant select, delete on public.categories to authenticated;
grant insert (id, name, owner_user_id, created_at) on public.categories to authenticated;
grant update (name) on public.categories to authenticated;

create policy categories_select on public.categories
  for select to authenticated
  using (owner_user_id is null or owner_user_id = (select auth.uid()));

create policy categories_insert_own on public.categories
  for insert to authenticated
  with check (owner_user_id = (select auth.uid()));

create policy categories_update_own on public.categories
  for update to authenticated
  using (owner_user_id = (select auth.uid()))
  with check (owner_user_id = (select auth.uid()));

create policy categories_delete_own on public.categories
  for delete to authenticated
  using (owner_user_id = (select auth.uid()));

-- ---------------------------------------------------------------------------
-- Ingredients: the global catalog, keyed by normalized name. Read-only for clients; the
-- service role (categorize-ingredients, M6) and private.ensure_ingredient write it.
-- ---------------------------------------------------------------------------

create table public.ingredients (
  normalized_name     text primary key,
  display_name        text not null,
  default_category_id uuid references public.categories,  -- null while pending
  status              text not null default 'pending' check (status in ('pending', 'categorized', 'failed')),
  is_grocery_item     boolean,                             -- null until categorized
  categorized_by      text,                                -- e.g. model id, 'seed', 'admin'
  attempts            int not null default 0,
  household_count     int not null default 0,              -- see spec 6.5
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);
create index ingredients_status_idx on public.ingredients (status) where status <> 'categorized';

create trigger ingredients_set_updated_at
  before insert or update on public.ingredients
  for each row execute function private.set_updated_at();

alter table public.ingredients enable row level security;

revoke all on table public.ingredients from anon, authenticated;
grant select on public.ingredients to authenticated;

create policy ingredients_select on public.ingredients
  for select to authenticated
  using (true);

-- Which households have used an ingredient, to maintain household_count. No client access.
create table public.ingredient_households (
  ingredient_name text references public.ingredients on delete cascade,
  household_id    uuid references public.households on delete cascade,
  primary key (ingredient_name, household_id)
);
create index ingredient_households_household_id_idx on public.ingredient_households (household_id);

alter table public.ingredient_households enable row level security;
revoke all on table public.ingredient_households from anon, authenticated;

-- ---------------------------------------------------------------------------
-- Per-user preferences (spec 4.3.2, 4.3.3). Never shared with the household.
-- ---------------------------------------------------------------------------

create table public.user_category_overrides (
  user_id         uuid references auth.users on delete cascade,
  ingredient_name text references public.ingredients,
  category_id     uuid not null references public.categories on delete cascade,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  primary key (user_id, ingredient_name)
);

create table public.user_category_order (
  user_id     uuid references auth.users on delete cascade,
  category_id uuid references public.categories on delete cascade,
  position    double precision not null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  primary key (user_id, category_id)
);

create trigger user_category_overrides_set_updated_at
  before insert or update on public.user_category_overrides
  for each row execute function private.set_updated_at();

create trigger user_category_order_set_updated_at
  before insert or update on public.user_category_order
  for each row execute function private.set_updated_at();

alter table public.user_category_overrides enable row level security;
alter table public.user_category_order enable row level security;

revoke all on table public.user_category_overrides from anon, authenticated;
revoke all on table public.user_category_order from anon, authenticated;
grant select, insert, update, delete on public.user_category_overrides to authenticated;
grant select, insert, update, delete on public.user_category_order to authenticated;

create policy user_category_overrides_own on public.user_category_overrides
  for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

create policy user_category_order_own on public.user_category_order
  for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

